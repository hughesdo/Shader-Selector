"""
Headless compile + render check of every shader in public/library.

  npm run dev            (in another terminal; or pass --url)
  python tools/selftest.py --url http://localhost:5180/

Writes tools/selftest_results.json and tools/compile_failures.txt (source .glsl
names, one per line) which the importer accepts via --exclude.
Requires: pip install playwright && playwright install chromium
"""
import argparse
import json
import time
from pathlib import Path

from playwright.sync_api import sync_playwright

HERE = Path(__file__).parent


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--url", default="http://localhost:5180/")
    ap.add_argument("--timeout", type=int, default=1800)
    ap.add_argument("--headed", action="store_true")
    a = ap.parse_args()

    with sync_playwright() as p:
        b = p.chromium.launch(
            headless=not a.headed,
            args=["--use-gl=angle", "--use-angle=swiftshader", "--enable-unsafe-swiftshader", "--ignore-gpu-blocklist"],
        )
        page = b.new_page(viewport={"width": 1280, "height": 900})
        page.on("pageerror", lambda e: print("pageerror:", e))
        page.goto(a.url.rstrip("/") + "/?selftest")
        t0 = time.time()
        last = 0
        while time.time() - t0 < a.timeout:
            st = page.evaluate("() => window.__selftest && { done: window.__selftest.done, n: window.__selftest.results.length }")
            if st:
                if st["n"] - last >= 25:
                    print(f"  {st['n']} done ({time.time() - t0:.0f}s)")
                    last = st["n"]
                if st["done"]:
                    break
            time.sleep(1)
        results = page.evaluate("() => window.__selftest ? window.__selftest.results : []")
        b.close()

    ok = [r for r in results if r["ok"]]
    bad = [r for r in results if not r["ok"]]
    (HERE / "selftest_results.json").write_text(json.dumps(results, indent=1))
    # map ids back to source file names via shader.json
    lib = HERE.parent / "public" / "library"
    names = []
    for r in bad:
        for f in lib.glob(f"shaders/*/*/{r['id']}/shader.json"):
            names.append(json.loads(f.read_text())["info"]["source"]["file"])
    (HERE / "compile_failures.txt").write_text("# generated by selftest.py\n" + "\n".join(sorted(set(names))) + "\n")
    print(f"{len(ok)} ok, {len(bad)} failed, of {len(results)}")
    for r in bad[:40]:
        first = (r.get("error") or "").strip().splitlines()
        print(f"  FAIL {r['id']}: {first[1] if len(first) > 1 else first[0] if first else ''}")


if __name__ == "__main__":
    main()
